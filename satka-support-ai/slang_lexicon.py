def match_slang_lexicon(text: str) -> str | None:
  """Быстрый матч по гигантской базе сленга."""
  cleaned = (text or "").strip()
  if not cleaned:
    return None

  low = cleaned.lower().rstrip("!?.…")
  low = re.sub(r"\s+", " ", low)

  exact = EXACT_SLANG_REPLIES.get(low)
  if exact:
    return exact

  for pattern, reply in SLANG_PATTERN_REPLIES:
    if pattern.search(cleaned):
      return reply

  return None


def random_filler() -> str:
  return random.choice(HUMAN_FILLERS)
